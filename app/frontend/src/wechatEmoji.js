function escapeAttr(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function escapeHtml(s) {
  return String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// 把文本中的 [code] 占位符替换成带样式的表情 span。
// 输入 text 应为「已 HTML 转义」的字符串（与 highlighted() 衔接，避免 XSS）。
// 仅命中映射表的 code 会被替换；未知 code 保留原样，不丢信息。
export function renderEmojiHtml(escapedText) {
  return String(escapedText || '').replace(/\[([^\]\n]+)\]/g, (m, code) => {
    const key = code.trim();
    const e = EMOJI_MAP[key];
    if (!e) return m; // 未知表情：保留 [code] 原文
    return `<span class="wx-emoji" title="${escapeAttr(key)}">${e}</span>`;
  });
}

// 判断一组消息里哪些是「纯表情」（整条只有表情占位符），用于卡片放大渲染
export function isPureEmoji(text) {
  if (!text) return false;
  const t = String(text).trim();
  if (!t) return false;
  return /^\[[^\]\n]+\](?:\[[^\]\n]+\])*$/.test(t);
}

// 用于「无需搜索高亮」的场景（详情面板等）：先转义再渲染表情，安全且无 XSS 风险。
export function renderEmojiText(raw) {
  return renderEmojiHtml(escapeHtml(raw));
}

